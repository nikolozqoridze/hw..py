# კომენტარების სახით ჩამთვალეთ ყველა შედარებითი ოპერატორები და გააკეთეთ 5-5 ნაგალითი თითოეულზე.
  
# 1) == (უდრის) - შეამოწმებს, არის თუ არა ორი მნიშვნელობა ერთმანეთის ტოლი.
#მაგალითები:
print(5 == 5) # True    



# 2) != (არ უდრის) - შეამოწმებს, არის თუ არა ორი მნიშვნელობა ერთმანეთის ტოლი.

#მაგალითები:
print(5 != 3) # True

# 3) > (მეტია) - შეამოწმებს, არის თუ არა ერთი მნიშვნელობა მეორეზე მეტია.
#მაგალითები:
print(10 > 5) # True


# 4) < (ნაკლებია) - შეამოწმებს, არის თუ არა ერთი მნიშვნელობა მეორეზე ნაკლებია.
#მაგალითები:
print(3 < 7) # True
# 5) >= (მეტია ან უდრის) - შეამოწმებს, არის თუ არა ერთი მნიშვნელობა მეორეზე მეტია ან უდრის. 
#მაგალითები:
print(5 >= 5) # True





# 3) კომენტარების სახით ახსენით რა არის logical operators, ჩამოწერეთ თითოეული და განმარტეთ რომელი რა დროს რა შედეგს გვიბრუნებს.
#and (და) - გამოიყენება იმის შესამოწმებლად, არის თუ არა ორივე პირობა მართალი. თუ ორივე პირობა მართალია, შედეგი იქნება True, წინააღმდეგ შემთხვევაში False.
#or (ან) - გამოიყენება იმის შესამოწმებლად, არის თუ არა ერთი პირობა მართალი. თუ ერთი პირობა მართალია, შედეგი იქნება True, წინააღმდეგ შემთხვევაში False.

# 4) გააკეთეთ 3-3 მაგალითი logical operator-ებზე.
print(5>10 or 10<5)
print(5>3 and 10<15)



# 5) მომხმარებელს შემოატანინეთ რიცხვი, შეინახეთ იგი ცვლადში და შეადარეთ იგი მეტია თუ არა თქვენს მიერ წინასწარ გამზადებულ რიცხვზე.
